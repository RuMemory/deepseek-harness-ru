// Р—Р°РїСѓСЃРє: node tools/build-client.mjs
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const RU = path.join(ROOT, "ru");
const OUT = path.join(ROOT, "lib", "client.js");

const files = fs.readdirSync(RU).filter(f => f.endsWith(".js")).sort();
if (!files.length) { console.error("ru/ РїСѓСЃС‚ вЂ” РЅРµС‡РµРіРѕ СЃРѕР±РёСЂР°С‚СЊ"); process.exit(1); }

const dicts = [];
for (const f of files) {
  const ns = f.replace(/\.js$/, "");
  const mod = await import(pathToFileURL(path.join(RU, f)).href + "?t=" + Date.now());
  const dict = mod.default;
  if (!dict || typeof dict !== "object" || Array.isArray(dict)) { console.error("РЅРµ СЃР»РѕРІР°СЂСЊ: " + f); process.exit(1); }
  dicts.push([ns, dict]);
}

const totalKeys = dicts.reduce((n, [, d]) => n + Object.keys(d).length, 0);

const registerLines = dicts.map(([ns], i) =>
  `    ctx.effect(() => ctx.locale.register(${JSON.stringify(ns)}, "ru", D[${i}]), "locale-ru: ${ns}");`
).join("\n");

const out = `// dsh-locale-ru вЂ” Russian language pack for the DSH web GUI.
// GENERATED by tools/build-client.mjs from ru/*.js вЂ” do not edit by hand.
window.__ModuleLoader__.load({
  id: "dsh-locale-ru",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    const D = [
${dicts.map(([, d]) => "      " + JSON.stringify(d)).join(",\n")}
    ];
    const NS = [
${dicts.map(([ns]) => "      " + JSON.stringify(ns)).join(",\n")}
    ];
    const inject = ["locale"];
    function apply(ctx) {
      ctx.effect(() => ctx.locale.addLanguage({ id: "ru", label: "Р СѓСЃСЃРєРёР№", fallback: "en" }), "locale-ru: language");
      for (let i = 0; i < D.length; i++) {
        const ns = NS[i], dict = D[i];
        ctx.effect(() => ctx.locale.register(ns, "ru", dict), "locale-ru: " + ns);
      }
    }
    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  }
});
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log("built " + OUT);
console.log("namespaces: " + dicts.length + ", keys: " + totalKeys + ", bytes: " + out.length);
// СЃРІРµСЂРєР° РїРѕРєСЂС‹С‚РёСЏ СЃ en-json
const EN = path.join(ROOT, "en-json");
if (fs.existsSync(EN)) {
  let missingTotal = 0;
  for (const f of fs.readdirSync(EN).filter(f => f.endsWith(".json"))) {
    const ns = f.replace(/\.json$/, "");
    const en = JSON.parse(fs.readFileSync(path.join(EN, f), "utf8"));
    const ru = dicts.find(([n]) => n === ns);
    if (!ru) { console.log("NO-RU-DICT: " + ns + " (" + Object.keys(en).length + " keys)"); missingTotal += Object.keys(en).length; continue; }
    const missing = Object.keys(en).filter(k => !(k in ru[1]));
    if (missing.length) { console.log("PARTIAL: " + ns + " missing " + missing.length + "/" + Object.keys(en).length); missingTotal += missing.length; }
  }
  console.log("coverage: " + (2915 - missingTotal) + "/2915");
}
